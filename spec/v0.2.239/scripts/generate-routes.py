def successor_path(by_id, s):
    # a successor is an id, or {id, query}: the path plus `?k=v&…`; a `:param` value stays a template token the
    # conductor's marker middleware substitutes with the deprecated path's own parameter (0.2.103)
    sid, q = (s, {}) if isinstance(s, str) else (s['id'], s.get('query') or {})
    p = by_id[sid]['path']
    return p + ('?' + '&'.join(f'{k}={v}' for k, v in q.items()) if q else '')


UNAUTH_RS = {w: ''.join(p.capitalize() for p in w.split('_')) for w in UNAUTHENTICATED}


def unauth_rs(r):
    """0.2.148: a door's `unauthenticated` answer: `Some(Unauthenticated::<Word>)`, or `None` (the refusal order's 401)."""
    w = r.get('unauthenticated')
    return f'Some(Unauthenticated::{UNAUTH_RS[w]})' if w else 'None'


def door_rs(r, path, note):
    """One DOORS row; an alias path gets its row's words (T12 W1: the alias's door is the row's). 0.2.150: the door
    names one permission (`None` = authenticated), a scope, its principals and its OBJECT checks."""
    return (f'    // {r["id"]}{note}\n'
            f'    Door {{ method: {rust_str(r["method"])}, path: {rust_str(path)}, '
            f'at: At::{AT_RS[r["at"]]}, permission: {permission_rs(r["permission"])}, '
            f'scope: Scope::{SCOPE_RS[r["scope"]]}, '
            f'principals: &[{", ".join("Principal::" + PRINCIPAL_RS[x] for x in r["principals"])}], '
            f'checks: &[{", ".join(check_rs(c) for c in r.get("checks") or [])}], '
            f'reads: Reads::{READS_RS[r["reads"]]}, '
            f'machine_reach: MachineReach::{MACHINE_REACH_RS[r.get("machine_reach", "path")]}, '
            f'release2: {str(bool(r.get("release2"))).lower()}, '
            f'org_level: {str(bool(r.get("org_level"))).lower()}, '
            f'unauthenticated: {unauth_rs(r)} }},\n')


def auth_rs(r):
    """0.2.145: a doorless row's `auth` word as `Some("…")`; `None` for a door row or a tombstone."""
    return f'Some({rust_str(r["auth"])})' if 'auth' in r else 'None'


