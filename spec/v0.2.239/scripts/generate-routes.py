    out = [HEADER_RS, '\n', 'use serde::{Deserialize, Serialize};\n\n',
           '/// The permission vocabulary (0.6 slice 2), one variant per word of the registry\'s PERMISSIONS.\n',
           '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]\n',
           '#[serde(rename_all = "snake_case")]\n', 'pub enum Permission {\n']
    out += [f'    {PERM_RS[p]},\n' for p in PERMISSIONS]
    out.append('}\n\nimpl Permission {\n    /// Every permission, in the registry\'s order.\n')
    out.append('    pub const ALL: &[Permission] = &[' + ', '.join(f'Permission::{PERM_RS[p]}' for p in PERMISSIONS) + '];\n\n')
    out.append('    /// The wire word.\n    pub fn as_str(self) -> &\'static str {\n        match self {\n')
    out += [f'            Permission::{PERM_RS[p]} => {rust_str(p)},\n' for p in PERMISSIONS]
    out.append('        }\n    }\n\n')
    out.append('    /// The DEPRECATED `requires` spelling of this permission (a fixed map, kept for 0.x).\n')
