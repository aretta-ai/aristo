def check_rs(word):
    return f'Check::{CHECK_RS[word]}'


def permission_rs(word):
    """A door's permission: `None` (authenticated: no permission) or `Some(Permission::<Word>)`."""
    if word == AUTHENTICATED:
        return 'None'
    if word not in PERM_RS:
        raise SystemExit(f'unknown permission {word!r}')
    return f'Some(Permission::{PERM_RS[word]})'


# 0.2.120: ONE function per list. Every writer (doors.rs, routes.rs, routes.json, paths.rs, routes.toml)
# AND generated/manifest.json take their rows from these, so the manifest cannot say what a writer did not do.
def served_rows(rows):
    """The rows the conductor serves: every row not marked specified-unbuilt (ROUTES)."""
    return [r for r in rows if not is_unbuilt(r)]


def unbuilt_rows(rows):
    """The rows marked specified-unbuilt (UNBUILT_ROUTES)."""
    return [r for r in rows if is_unbuilt(r)]


def door_rows(rows, served=True):
    """The door rows (`at`) of the served rows (DOORS) or of the unbuilt rows (UNBUILT_DOORS)."""
    return [r for r in (served_rows(rows) if served else unbuilt_rows(rows)) if 'at' in r]


def consumer_rows(rows, caller):
    """The served rows a consumer artefact declares: the dashboard (`page`), the CLI (`cli`), the plugin (`seat`)."""
    return [r for r in served_rows(rows) if caller in (r.get('callers') or [])]


def manifest_json(rows, version):
    """0.2.120: what the generator WROTE, as data (the operator's word 2026-10-18: no text-scrape checks). validate.py
    compares the registry's marks against this; the generated files themselves are proven by regeneration drift."""
    ids = lambda rs: [r['id'] for r in rs]
    return json.dumps({
        'spec': version,
        'served': ids(served_rows(rows)),
        'unbuilt': ids(unbuilt_rows(rows)),
        'doors': ids(door_rows(rows, True)),
        'unbuilt_doors': ids(door_rows(rows, False)),
        'consumers': {
            'dashboard': ids(consumer_rows(rows, 'page')),
            'cli': ids(consumer_rows(rows, 'cli')),
            'plugin': ids(consumer_rows(rows, 'seat')),
        },
        'generated_schemas': [E.path(r[0], r[1]) for r in E.rows()],
    }, indent=2) + '\n'


def rust_str(s):
    return json.dumps(s)  # a JSON string literal is a valid Rust string literal for these paths


def doors_rs(rows):
    out = [HEADER_RS,
           '//! THE DOOR TABLE\'s rows (`crate::doors::DOORS`): one per registry row that is a door (it has\n'
           '//! an `at`), in the registry\'s order, each followed by one per alias path with the row\'s words.\n'
           '//! The words are the registry\'s; the types are `crate::doors`\'s.\n\n',
           'use crate::doors::{At, Check, Door, MachineReach, Principal, Reads, Scope, Unauthenticated};\n',
           'use crate::facts::Permission;\n\n',
           'pub const DOORS: &[Door] = &[\n']
    def emit(door_list):
        for r in door_list:
            for path, note in [(r['path'], '')] + [(a['path'], ' (alias)') for a in r.get('aliases') or []]:
                out.append(door_rs(r, path, note))
    emit(door_rows(rows, True))
    out.append('];\n\n')
    out.append('/// The door rows of the registry\'s SPECIFIED-UNBUILT rows (README: a consumer never mounts or serves one;\n'
               '/// its contract check fails on an unbuilt row that is bound, or a built row still marked).\n')
    out.append('pub const UNBUILT_DOORS: &[Door] = &[\n')
    emit(door_rows(rows, False))
    out.append('];\n')
    # 0.2.170: the field-level doors (registry_vocab FIELD_DOORS), checked after the row's own door
    out.append('\n/// registry_vocab FIELD_DOORS (0.2.170; 0.2.214: `query`): (row id, where: body | header | query, name, value, the extra permission that\n'
               '/// value needs at the row\'s scope). Checked after the row\'s own door; the refusal is `forbidden` with `requires`.\n'
               '/// A value that is a BODY_GRAMMARS / QUERY_SELECTORS parse word (0.2.214) names the field\'s typed parse, not an enum word.\n')
    out.append('pub const FIELD_DOORS: &[(&str, &str, &str, &str, Permission)] = &[\n')
    for rid, wh, fld, val, perm in FIELD_DOORS:
        out.append(f'    ({rust_str(rid)}, {rust_str(wh)}, {rust_str(fld)}, {rust_str(val)}, Permission::{PERM_RS[perm]}),\n')
    out.append('];\n')
    out.append('\n/// registry_vocab HEADER_SELECTORS (0.2.170): (request header, the vocabulary tuple of its values).\n')
    out.append('pub const HEADER_SELECTORS: &[(&str, &str)] = &[' + ', '.join(f'({rust_str(h)}, {rust_str(t)})' for h, t in HEADER_SELECTORS) + '];\n')
    out.append('\n/// registry_vocab QUERY_SELECTORS (0.2.214 §4): (query parameter, the vocabulary tuple its typed parse comes from).\n')
    out.append('pub const QUERY_SELECTORS: &[(&str, &str)] = &[' + ', '.join(f'({rust_str(q)}, {rust_str(t)})' for q, t in QUERY_SELECTORS) + '];\n')
    out.append('\n/// registry_vocab BODY_GRAMMARS (0.2.214 §1): (body field with no enum, the vocabulary tuple its typed parse comes from).\n')
    out.append('pub const BODY_GRAMMARS: &[(&str, &str)] = &[' + ', '.join(f'({rust_str(f)}, {rust_str(t)})' for f, t in BODY_GRAMMARS) + '];\n')
    return ''.join(out)


def capabilities_rs():
    """T0b #1: the ONE Capability enum, generated from CAPS; the wire spelling from CAP_WIRE (serde rename + alias)."""
    out = [HEADER_RS, '\n', 'use serde::{Deserialize, Serialize};\n\n',
           '/// The capability vocabulary (CAPABILITY-MODEL §2), one variant per word of the registry\'s CAPS.\n',
           '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]\n',
           'pub enum Capability {\n']
    for c in CAPS:
        if c in CAP_WIRE:
            out.append(f'    #[serde(rename = {rust_str(CAP_WIRE[c])}, alias = {rust_str(CAP_RS[c])})]\n')
        out.append(f'    {CAP_RS[c]},\n')
    out.append('}\n\n')
    out.append('impl Capability {\n    /// Every capability, in the registry\'s order.\n')
    out.append('    pub const ALL: &[Capability] = &[' + ', '.join(f'Capability::{CAP_RS[c]}' for c in CAPS) + '];\n}\n')
    return ''.join(out)


